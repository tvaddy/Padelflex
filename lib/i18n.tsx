interface I18nContextType {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  t: typeof translations.no;
  isEnglish: boolean;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

const LANGUAGE_STORAGE_KEY = 'padelflex_language_pref';

/**
 * Provider that receives runtime initialLocale from server-side RootLayout
 * and synchronizes with localStorage user preferences.
 */
export function I18nProvider({ 
  initialLocale = 'no', 
  children 
}: { 
  initialLocale?: Locale; 
  children: React.ReactNode;
}) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
        if (saved === 'en' || saved === 'no') {
          return saved;
        }
      } catch {
        // Ignore localStorage errors
      }
    }
    return initialLocale;
  });

  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === LANGUAGE_STORAGE_KEY && (e.newValue === 'en' || e.newValue === 'no')) {
        setLocaleState(e.newValue);
      }
    };
    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, []);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, newLocale);
    } catch {
      // Ignore
    }
  };

  const toggleLocale = () => {
    const next: Locale = locale === 'en' ? 'no' : 'en';
    setLocale(next);
  };

  const t = translations[locale] || translations.no;
  const isEnglish = locale === 'en';

  return (
    <I18nContext.Provider value={{ locale, setLocale, toggleLocale, t, isEnglish }}>
      {children}
    </I18nContext.Provider>
  );
}

/**
 * Hook providing access to the current active locale, translation map, and toggle function.
 */
export function useTranslation() {
  const context = useContext(I18nContext);
  if (context) {
    return context;
  }
  // Safe fallback if used outside I18nProvider
  const fallbackLocale: Locale = DEFAULT_LOCALE;
  const t = translations[fallbackLocale] || translations.no;
  return {
    locale: fallbackLocale,
    setLocale: () => {},
    toggleLocale: () => {},
    t,
    isEnglish: fallbackLocale === 'en'
  };
}
